const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_EXECUTABLE,headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
  await page.route('https://**/*',route=>route.abort());
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
  assert.equal(await page.locator('h1').textContent(),'Prefab Homes Built Around Your Life.');
  assert.equal(await page.locator('.source-value-strip svg').count(),3);
  assert.equal(await page.locator('.source-benefits-grid article').count(),8);
  assert.equal(await page.locator('.source-benefits-grid article svg').count(),8);
  assert.equal(await page.locator('.home-process-details .process-steps article').count(),4);
  assert.equal(await page.locator('.home-specifications .specifications-grid article').count(),3);
  await page.waitForFunction(()=>document.querySelector('.source-benefits-grid article')?.classList.contains('reveal-target'));
  const target=page.locator('.source-benefits-grid article').last();
  await target.scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>{const el=[...document.querySelectorAll('.source-benefits-grid article')].at(-1);return el.classList.contains('is-revealed')&&getComputedStyle(el).opacity==='1';});
  await page.locator('.source-benefits-grid').screenshot({path:'test-results/details-benefits-desktop.png',animations:'disabled'});
  assert.ok(await page.locator('.reading-progress').evaluate(el=>Number(getComputedStyle(el).transform.match(/matrix\(([^,]+)/)[1])>.05));
  await page.getByRole('button',{name:'Scroll to top',exact:true}).click();
  await page.waitForFunction(()=>scrollY<2);
  assert.match(await target.getAttribute('class'),/is-revealed/);
  await page.getByRole('navigation',{name:'Main navigation',exact:true}).getByRole('link',{name:'About Us',exact:true}).click();
  await page.waitForURL('**/about-us');
  assert.equal(await page.locator('.process-details .process-steps article').count(),4);
  for(const article of await page.locator('.process-steps article').all())await article.scrollIntoViewIfNeeded();
  await page.locator('.process-details').screenshot({path:'test-results/details-process-desktop.png',animations:'disabled'});
  await page.goto('http://localhost:3000/designs');
  assert.equal(await page.locator('.specifications-details .specifications-grid article').count(),3);
  assert.match(await page.locator('.specifications-details').textContent(),/12 × 20 ft · 12 × 40 ft/);
  await page.goto('http://localhost:3000/contact');
  assert.equal(await page.locator('.checklist-details article').count(),3);
  await page.goto('http://localhost:3000/who-we-serve');
  assert.equal(await page.locator('.audience-details-grid article').count(),6);
  assert.equal(await page.locator('.serve-artwork').count(),6);
  await page.setViewportSize({width:390,height:844});
  for(const article of await page.locator('.audience-details-grid article').all())await article.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.locator('.audience-details').screenshot({path:'test-results/details-audience-mobile.png',animations:'disabled'});
  assert.deepEqual(errors,[]);
  const reduced=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
  await reduced.route('https://**/*',route=>route.abort());
  await reduced.goto('http://localhost:3000',{waitUntil:'networkidle'});
  assert.equal(await reduced.locator('.source-benefits-grid article').evaluateAll(nodes=>nodes.every(el=>getComputedStyle(el).opacity==='1')),true);
  await reduced.evaluate(()=>scrollTo(0,1200));
  await reduced.getByRole('button',{name:'Scroll to top',exact:true}).click();
  await reduced.waitForFunction(()=>scrollY<2);
  console.log('PASS: document-based details and SVGs, first-visit scroll reveals, no replay flicker on upward scroll, reading progress, back-to-top, route changes, mobile layout, and reduced-motion visibility.');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1)});
